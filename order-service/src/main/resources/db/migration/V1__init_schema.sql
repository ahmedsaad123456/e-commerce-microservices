-- "order" is a reserved word in SQL, so the table is called "orders"
CREATE TABLE orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference      UUID           NOT NULL,   -- one per create-order attempt, also the purchase id
    customer_id    VARCHAR(64)    NOT NULL,   -- id from the Customer service (Mongo): no foreign key across databases
    total_amount   NUMERIC(14, 2) NOT NULL,
    payment_method VARCHAR(30)    NOT NULL,
    status         VARCHAR(20)    NOT NULL,
    created_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uq_orders_reference UNIQUE (reference),
    CONSTRAINT ck_orders_total CHECK (total_amount >= 0)
);

CREATE TABLE order_line (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL,
    product_id   BIGINT         NOT NULL,
    product_name VARCHAR(150)   NOT NULL,   -- snapshot: the product may be renamed later
    unit_price   NUMERIC(12, 2) NOT NULL,   -- snapshot: the price may change later
    quantity     INTEGER        NOT NULL,
    CONSTRAINT fk_order_line_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT ck_order_line_quantity CHECK (quantity > 0)
);

CREATE INDEX idx_orders_customer_id ON orders (customer_id);
CREATE INDEX idx_order_line_order_id ON order_line (order_id);