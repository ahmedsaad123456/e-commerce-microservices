package com.example.order_service.outbox;

import jakarta.persistence.*;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import org.springframework.data.domain.Persistable;

import java.time.Instant;
import java.util.UUID;

@Entity
@Table(name = "outbox_events")
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class OutboxEvent implements Persistable<UUID> {

    @Id
    private UUID id;                                  // assigned by us, not generated by the DB

    @Column(nullable = false, length = 50)  private String aggregateType;
    @Column(nullable = false, length = 64)  private String aggregateId;
    @Column(nullable = false, length = 100) private String topic;
    @Column(nullable = false, columnDefinition = "text") private String payload;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private OutboxStatus status;

    // the existing "topic" field holds the Kafka topic, or the RabbitMQ EXCHANGE when destination = RABBITMQ
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private OutboxDestination destination;

    @Column(length = 100)
    private String routingKey;

    @Column(nullable = false) private int attempts;
    @Column(insertable = false, updatable = false) private Instant createdAt;   // filled by the DB default
    private Instant publishedAt;

    // Because we assign the id ourselves, Spring Data cannot tell "new" from "existing" and would run a
    // useless SELECT before every INSERT. Persistable tells it explicitly.
    @Transient private boolean isNew = true;
    @Override public boolean isNew() { return isNew; }
    @PostLoad @PostPersist void markNotNew() { this.isNew = false; }

    public static OutboxEvent pending(UUID id, String aggregateType, String aggregateId, String topic, String payload) {
        var e = new OutboxEvent();
        e.id = id; e.aggregateType = aggregateType; e.aggregateId = aggregateId;
        e.topic = topic; e.payload = payload; e.status = OutboxStatus.PENDING;
        e.destination = OutboxDestination.KAFKA;
        return e;
    }

    public static OutboxEvent pendingRabbit(UUID id, String aggregateType, String aggregateId,
                                            String exchange, String routingKey, String payload) {
        var e = pending(id, aggregateType, aggregateId, exchange, payload);
        e.destination = OutboxDestination.RABBITMQ;
        e.routingKey = routingKey;
        return e;
    }

    public void markPublished() { this.status = OutboxStatus.PUBLISHED; this.publishedAt = Instant.now(); }
    public void recordFailure() { this.attempts++; }
}