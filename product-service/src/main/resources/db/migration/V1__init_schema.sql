CREATE TABLE category (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    CONSTRAINT uq_category_name UNIQUE (name)
);

CREATE TABLE product (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(150)   NOT NULL,
    description        VARCHAR(255),
    price              NUMERIC(12, 2) NOT NULL,
    available_quantity INTEGER        NOT NULL DEFAULT 0,
    category_id        BIGINT         NOT NULL,
    CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES category (id),
    CONSTRAINT ck_product_price    CHECK (price >= 0),
    -- last line of defence against overselling, even if the code has a bug
    CONSTRAINT ck_product_quantity CHECK (available_quantity >= 0)
);

CREATE INDEX idx_product_category_id ON product (category_id);

-- one row per (purchase, product): used for idempotency
CREATE TABLE stock_movements (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id UUID           NOT NULL,
    product_id  INTEGER         NOT NULL,
    quantity    INTEGER        NOT NULL,
    unit_price  NUMERIC(12, 2) NOT NULL,
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT fk_stock_movements_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_stock_movements_quantity CHECK (quantity > 0),
    CONSTRAINT uq_stock_movements_purchase_product UNIQUE (purchase_id, product_id)
);